#!/usr/bin/env python3
"""Regenerate src/entities.inc (the HTML5 named-entity table).

Run from the repository root:  scripts/gen-entities.py
The table is sorted by name so parser.c can binary-search it.
"""

from html.entities import html5


def c_string(value: str) -> str:
    out = []
    for b in value.encode("utf-8"):
        if b == 0x22:
            out.append('\\"')
        elif b == 0x5C:
            out.append("\\\\")
        elif 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            out.append("\\%03o" % b)
    return "".join(out)


def main():
    entries = sorted(
        (name[:-1], value) for name, value in html5.items() if name.endswith(";")
    )

    lines = [
        "/* Generated by scripts/gen-entities.py from the HTML5 named-entity set.",
        " * Sorted by name; binary-searched by parser.c. Do not edit by hand. */",
        "static const MdEntity ENTITY_TABLE[] = {",
    ]
    for name, value in entries:
        lines.append('    {"%s", "%s"},' % (name, c_string(value)))
    lines.append("};")
    lines.append("")

    with open("src/entities.inc", "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {len(entries)} entities to src/entities.inc")


if __name__ == "__main__":
    main()
